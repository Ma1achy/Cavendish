"""Table "Cavendish's polyhedral kernel" (P1-P7) from the kernel's validation cases.

    python scripts/engine_table.py       # called by `make.py engine`; writes generated/rr-engine.tex

Reads the records the cases themselves write (cav-core, src/polyhedral/tests.rs; `make.py engine`
runs them alone with `CAV_VALIDATION_DIR=data/cavendish/engine`, the same records
`cargo xtask validate` collects into docs/validation/report.json) and takes each row's measured
number from its case. The criteria are the cases' tolerances; each case's control arm is a test
beside it (docs/slices/S5.md §3, rows P1-P7).
"""

from __future__ import annotations

import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
REPO = HERE.parents[2]
RECORDS = HERE / "data" / "cavendish" / "engine"

# (row, what is checked, the cases measured, how the measured cell reads, the criterion's words)
ROWS: tuple[tuple[str, str, tuple[str, ...], str, str], ...] = (
    ("P1", "a box is Nagy's prism (64 points, 0.15--3 sides)", ("polyhedral.the_prism",),
     r"$V$, $\mathbf{{g}}$ {0}", r"$\le{t0}$; a flipped face fails"),
    ("P2", "far field against the cube series", ("polyhedral.far_field", "polyhedral.far_field_at_ten_thousand"),
     r"{0} worst at $R/s=10$--$10^3$; {1} at $10^4$",
     r"$\le{t0}$; $\le{t1}$; triple product $\ge10\times$ worse at $10^4$"),
    ("P3", r"$L_e$, $V$, $\mathbf{g}$ at $10^{-4}$--$10^{-8}$~m from an edge", ("polyhedral.near_edge",),
     "{0}", r"$\le{t0}$; direct form loses $\ge10^{{-7}}$"),
    ("P4", "on a face, edge, vertex, edge extension", ("polyhedral.on_its_surface",),
     r"finite; worst change {0} at $10^{{-9}}s$", r"$\le{t0}$"),
    ("P5", r"$\sum_f\omega_f = 0$, $4\pi$, $2\pi$ (out, in, on a face)", ("polyhedral.solid_angles",),
     "{0}", r"$\le{t0}$; a flipped face fails"),
    ("P6", r"$\mathbf{g} = -\nabla V$ (central difference)", ("polyhedral.attraction_is_the_gradient",),
     "{0}", r"$\le{t0}$; a flipped face fails"),
    ("P7", "a mesh's moments to third order", ("polyhedral.mesh_moments",), "{0}", r"$\le{t0}$"),
)


def sci(x: float) -> str:
    """`$2.8\\times10^{-14}$`; a power of ten alone as `$10^{-13}$`."""
    if x == 0.0:
        return "$0$"
    e = math.floor(math.log10(abs(x)))
    m = x / 10.0**e
    if abs(m - 1.0) < 1e-9:
        return f"$10^{{{e}}}$"
    return f"${m:.1f}\\times10^{{{e}}}$"


def power(x: float) -> str:
    """A tolerance as `10^{-13}` (inside the caller's math)."""
    return f"10^{{{round(math.log10(x))}}}"


def record(path: pathlib.Path) -> dict[str, object]:
    """One case's record (`key<TAB>value` lines), with its numbers as floats and its verdict."""
    fields = dict(line.split("\t", 1) for line in path.read_text(encoding = "utf-8").splitlines() if line)
    return {"name": fields["name"], "measured": float(fields["measured"]),
            "tolerance": float(fields["tolerance"]), "status": "pass" if fields["pass"] == "true" else "fail"}


def main() -> None:
    cases = {str(c["name"]): c for c in map(record, sorted(RECORDS.iterdir()))}
    lines = [r"% generated by scripts/engine_table.py from the polyhedral.* cases' records "
             r"(data/cavendish/engine)",
             r"\begin{tabular}{>{\raggedright}p{0.38\linewidth}>{\raggedright}p{0.26\linewidth}"
             r">{\raggedright\arraybackslash}p{0.26\linewidth}}\toprule",
             r"check & measured & criterion\\\midrule"]
    for row, what, names, measured, criterion in ROWS:
        found = [cases[n] for n in names]
        assert all(c["status"] == "pass" for c in found), f"{row}: a case does not pass"
        cell = measured.format(*(sci(float(c["measured"])) for c in found))  # type: ignore[arg-type]
        crit = criterion.format(**{f"t{k}": power(float(c["tolerance"])) for k, c in enumerate(found)})  # type: ignore[arg-type]
        lines.append(f"{row}: {what} & {cell} & {crit}\\\\")
    lines[-1] += r"\bottomrule"
    lines.append(r"\end{tabular}")
    out = HERE / "generated" / "rr-engine.tex"
    out.write_text("\n".join(lines) + "\n", encoding = "utf-8")
    print(out.name, "from", len(ROWS), "rows")


if __name__ == "__main__":
    main()
