"""Write the paper's scene files: the benchmark bodies as Cavendish scenes, so the figures can be
regenerated by Cavendish itself once S5 has the polyhedral kernel and fill moments.

Each scene holds one body as a mesh held in the scene (`Triangles`, the exact triangles of
`skin_bench.body(name)`, ρ = 2700 kg/m³) at the origin, and three towers whose bases sit at
distance D from the body's centre along the benchmark's three directions, so tower k's lower arm
starts where the benchmark's lower read point k is. Pitch 1/64 m, supersample 4 (today's sampled
fill); S5 adds the representation as a field of the body.

    python scripts/make_scenes.py            # writes scenes/<body>-<D>m.ron

Check each with `cav get scenes/<file>.ron` (the loader validates the mesh and the spec).
"""

from __future__ import annotations

import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "research" / "exact-skin-and-partial-fill"))
import skin_bench  # noqa: E402

BODIES = ("cube_aligned", "cube", "icosahedron", "plate", "sphere")
DISTANCES = (1.5, 10.0)
RHO = 2700.0


def mesh(tris: np.ndarray) -> tuple[list[tuple[float, float, float]], list[tuple[int, int, int]]]:
    verts: dict[tuple[float, float, float], int] = {}
    faces = []
    for t in tris:
        idx = []
        for p in t:
            key = (float(p[0]), float(p[1]), float(p[2]))
            idx.append(verts.setdefault(key, len(verts)))
        faces.append((idx[0], idx[1], idx[2]))
    return list(verts), faces


def tower(label: str, pos: np.ndarray) -> str:
    return f"""            (
                label: "{label}",
                position: ({float(pos[0])!r}, {float(pos[1])!r}, {float(pos[2])!r}),
                timing: (
                    offset: 0.0,
                ),
                instrument: None,
            ),"""


def scene(name: str, dist: float) -> str:
    tris = skin_bench.body(name)
    vol, _ = skin_bench.volume_centroid(tris, np.zeros(3))
    verts, faces = mesh(tris)
    towers = "\n".join(tower(f"tower {k + 1}", dist * u) for k, u in enumerate(skin_bench.DIRECTIONS))
    vtext = ",\n".join(f"                        ({v[0]!r}, {v[1]!r}, {v[2]!r})" for v in verts)
    ftext = ",\n".join(f"                        ({a}, {b}, {c})" for a, b, c in faces)
    tag = f"{name}-{dist:g}m"
    return f"""// Paper scene `{tag}` (docs/papers/polyhedral-gravity), written by scripts/make_scenes.py from
// the research benchmark's body `{name}` (docs/research/exact-skin-and-partial-fill/skin_bench.py).
// Frame: metres, x east, y north, z up; seconds. Body at the origin; tower k's base at {dist:g} m
// along the benchmark's direction k. Regenerate rather than edit.
(
    version: 1,
    name: "{tag}",
    description: "Benchmark body {name} (rho 2700 kg/m^3, {len(faces)} triangles) seen by three towers {dist:g} m from its centre, for the polyhedral-gravity paper.",
    duration: 4.0,
    array: (
        instrument: (
            tower_height: 10.1,
            ifo_separation: 5.0,
            half_sequence: 0.73,
            launch_velocity: 3.86,
            cycle: 2.0,
            atom_mass: 1.4431558652473234e-25,
            gravity: 9.81,
            kicks: 1000,
            launch_floor: true,
            sign: LowerMinusUpper,
        ),
        towers: [
{towers}
        ],
        schedule: (
            jitter: None,
            alternate: None,
            gaps: None,
            window: None,
            loss: 0.0,
            seed: 0,
        ),
    ),
    room: None,
    floor: None,
    bodies: [
        (
            label: "{name}",
            mass: {float(RHO * vol)!r},
            radius: 0.0,
            shape: Some((
                kind: Triangles(
                    vertices: [
{vtext},
                    ],
                    triangles: [
{ftext},
                    ],
                ),
                pitch: 0.015625,
                supersample: 4,
                material: None,
                parts: [],
            )),
            motion: Static(
                position: (0.0, 0.0, 0.0),
            ),
            appears: None,
            vanishes: None,
        ),
    ],
)
"""


def main() -> None:
    out = HERE.parent / "scenes"
    out.mkdir(exist_ok=True)
    for name in BODIES:
        for dist in DISTANCES:
            path = out / f"{name}-{dist:g}m.ron"
            path.write_text(scene(name, dist), encoding="utf-8", newline="\n")
            print(path.name)


if __name__ == "__main__":
    main()
