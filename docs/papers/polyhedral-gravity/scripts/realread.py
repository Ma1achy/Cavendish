def table_conv(conv: dict) -> dict[str, float]:
    """Table 2: real read at 1.5 m and 10 m, h = 1/64 m; returns the numbers the text quotes."""
    rows = [r"\begin{tabular}{l" + "r" * len(BODIES) + "}", r"\toprule",
            "representation & " + " & ".join(BODY_NAME[b] for b in BODIES) + r" \\"]
    for dist in ("1.5", "10.0"):
        rows.append(r"\midrule")
        rows.append(r"\multicolumn{6}{l}{\textit{tower axis " + dist.rstrip("0").rstrip(".")
                    + r" m from the centre}} \\")
        def signed(b: str, read: str) -> str:
            # The signal of the direction with the largest flight read, with its sign (referee,
            # draft 4: the flight read changes sign between 1.5 m and 10 m; the leading does not).
            by = conv[b][dist]["real"]["signal_by_direction"]
            k = max(range(len(by)), key=lambda i: abs(by[i]))
            x = conv[b][dist][read]["signal_by_direction"][k]
            return f"{x:+#.3g}".replace("+", "$+$").replace("-", "$-$")

        sig = " & ".join(f"{signed(b, 'real')} ({signed(b, 'leading')})" for b in BODIES)
        rows.append(f"signal, flight (leading) read (rad) & {sig} \\\\")
        for rep, label in REPS:
            cells = []
            for b in BODIES:
                r = conv[b][dist]["real"]["reps"][rep]
                cells.append(f"{sci(r['err'][-1])} ({r['order']:.1f})")
            rows.append(f"{label} & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    write("rr-conv.tex", rows, "data/level/conv.json (scripts/conv_level.py)")

    def worst(rep: str, dist: str = "1.5") -> tuple[float, str]:
        vals = [(conv[b][dist]["real"]["reps"][rep]["err"][-1], b) for b in BODIES]
        return max(vals)

    out = {"sig_max": max(conv[b]["1.5"]["real"]["signal"] for b in BODIES),
           "sig_min": min(conv[b]["1.5"]["real"]["signal"] for b in BODIES if b != "plate"),
           "sig_plate": conv["plate"]["1.5"]["real"]["signal"],
           "lead_max": max(abs(conv[b]["1.5"]["leading"]["signal"]) for b in BODIES)}
    for rep, _ in REPS:
        out[f"worst_{rep}"], out[f"worstbody_{rep}"] = worst(rep)  # type: ignore[assignment]
    ac = conv["cube_aligned"]["1.5"]["real"]["reps"]
    out["aligned_ss4"] = ac["ss4"]["err"][-1]
    out["aligned_cen"] = ac["frac_cen"]["err"][-1]
    out["aligned_q"] = ac["frac_cen_q"]["err"][-1]
    for rep, _ in REPS:
        for dist in ("1.5", "10.0"):
            orders = [conv[b][dist]["real"]["reps"][rep]["order"] for b in BODIES]
            out[f"orders_{rep}_{dist}"] = (min(orders), max(orders))  # type: ignore[assignment]
    out["clearance"] = min(min(conv[b]["clearance"][:3]) for b in BODIES)
    return out


def fig_convergence(conv: dict) -> None:
    shown = [r for r in REPS]
    colours = [BLUE, ORANGE, SKY, GREEN, VERMILION]
    fig, axes = plt.subplots(1, 3, figsize=(6.8, 2.45), sharey=True)
    for ax, name in zip(axes, ("cube_aligned", "cube", "sphere")):
        reps = conv[name]["1.5"]["real"]["reps"]
        lead = conv[name]["1.5"]["leading"]["reps"]
        ns = reps["ss4"]["n"]
        h = [1.0 / n for n in ns]
        for k, (rep, label) in enumerate(shown):
            ax.loglog(h, reps[rep]["err"], marker=MARKERS[k], color=colours[k], label=label)
            ax.loglog(h, lead[rep]["err"], ls=":", lw=0.9, color=colours[k])
        ax.set_title(BODY_NAME[name], fontsize=8, color=INK)
        ax.set_xlabel("pitch $h$ (m)")
        ax.set_xticks(h, [f"1/{n}" for n in ns])
        ax.minorticks_off()
    axes[0].set_ylabel("phase error, tower 1.5 m off (rad)")
    handles, labels = axes[0].get_legend_handles_labels()
    handles.append(plt.Line2D([], [], color=INK2, ls=":", lw=0.9))
    labels.append("leading read, same placements")
    fig.legend(handles, labels, loc="upper center", ncol=3, bbox_to_anchor=(0.5, 1.15), fontsize=7)
    fig.subplots_adjust(wspace=0.08)
    fig.savefig(FIG / "convergence.pdf")
    plt.close(fig)


