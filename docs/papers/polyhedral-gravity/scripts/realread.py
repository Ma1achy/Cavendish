def at(d: np.ndarray, y: np.ndarray, x: float) -> float:
    return float(np.exp(np.interp(np.log(x), np.log(d), np.log(np.maximum(y, 1e-300)))))


def table_decimation() -> dict[str, float]:
    chk = json.loads((STUDY / "mesh-check.json").read_text(encoding="utf-8"))
    dist = json.loads((RR / "data" / "exact-distance.json").read_text(encoding="utf-8"))
    rows = [r"\begin{tabular}{lrrrrrrrl}", r"\toprule",
            r"mesh & original & used & \multicolumn{2}{c}{original $\to$ used (m)} & vertices & "
            r"volume & signal & verdict \\",
            r"\cmidrule(lr){4-5}",
            r" & triangles & triangles & max & RMS & beyond 3.9 mm & change & change (rad) & \\",
            r"\midrule"]
    out = {}
    for n, label in (("dragon", "dragon"), ("armadillo", "Armadillo"), ("buddha", "Buddha")):
        dec = chk[n]["decimation"]
        r, full = dist[n], dist[f"{n} (full)"]
        diff = np.abs(np.array(r["exact"]) - np.array(full["exact"]))
        change = at(np.array(r["d"]), diff, 1.5)
        out[n] = change
        rows.append(
            f"{label} & {dec['original_triangles']:,} & {dec['decimated_triangles']:,} & ".replace(",", "\\,")
            + f"{sci(dec['max_original_to_decimated_m'])} & {sci(dec['rms_original_to_decimated_m'])} & "
            f"{dec['original_vertices_beyond_tol']:,} & ".replace(",", "\\,")
            + f"{sci(dec['volume_rel'])} & {sci(change)} & "
            + ("pass" if dec["passed"] else r"\textbf{fail}") + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    write("rr-decimation.tex", rows, "exact-skin-and-partial-fill/shapes/mesh-check.json, "
          "paper-real-read/data/exact-distance.json")
    return out


