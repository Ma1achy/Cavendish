def table_sweep() -> dict[str, object]:
    secs = md_sections(RR / "tables-sweep.md")
    body = section(secs, "1.5 m")
    cols = ["(a)", "(b)", "(c)", "(d)", "(e)", "(c★)", "(d★)"]
    rows = [r"\begin{tabular}{lr" + "r" * len(cols) + "}", r"\toprule",
            r"shape & signal & (a) & (b) & (c) & (d) & (e) & (c$^\star$) & (d$^\star$) \\", r"\midrule"]
    d_vals, c_vals, b_vals, b_orders, d_orders = [], [], [], [], []
    for r in body[1:]:
        if r[1] != "real":
            continue
        shape = r[0]
        cells = [f"{num(r[2]):+.1f}"]
        for k, cell in enumerate(r[3:10]):
            if not cell:
                cells.append("")
                continue
            v, o, _ = rms_order(cell)
            if cols[k] == "(e)":
                cells.append(f"$\\leq${sci(v, 0)}")
            else:
                cells.append(f"{sci(v)} ({o:.1f})")
            if shape not in ("sphere", "torus"):
                if cols[k] == "(d)":
                    d_vals.append(v)
                    d_orders.append(o)
                if cols[k] == "(c)":
                    c_vals.append(v)
                if cols[k] == "(b)":
                    b_vals.append(v)
                    b_orders.append(o)
        rows.append(f"{NAME[shape]} & " + " & ".join(cells) + r" \\")
        if shape == "torus":
            rows.append(r"\midrule")
    rows += [r"\bottomrule", r"\end{tabular}"]
    write("rr-sweep.tex", rows, "docs/research/paper-real-read/tables-sweep.md (analyse_real.py sweep)")
    return {"d": (min(d_vals), max(d_vals)), "c": (min(c_vals), max(c_vals)),
            "b": (min(b_vals), max(b_vals)), "b_order": (min(b_orders), max(b_orders)),
            "d_order": (min(d_orders), max(d_orders))}


def table_cost() -> None:
    secs = md_sections(RR / "tables-sweep.md")
    t = section(secs, "Table 5 with the real read")
    shapes = t[0][1:]
    by = {r[0]: r[1:] for r in t[1:]}

    def fmt(s: str) -> str:
        s = s.strip()
        if s in ("—", "n/a", ""):
            return "---"
        x = float(s)
        if x >= 100:
            return f"{x:,.0f}".replace(",", "\\,")
        return f"{x:.2g}"

    rows = [r"\begin{tabular}{lrrrrr}", r"\toprule",
            r"shape & (b) sampled fill & (c) fill + centroid & (d) \cutcell & (e) clipped pieces"
            r" & whole mesh \\", r"\midrule"]
    for k, s in enumerate(shapes):
        cells = []
        for tech in ("(b) sampled fill", "(c) fill at centroid", "(d) + second moment"):
            cells.append(" / ".join(fmt(x) for x in by[tech][k].split("/")))
        cells.append(fmt(by["(e) clipped pieces"][k].split("/")[0]))
        cells.append(fmt(by["whole mesh, direct"][k]))
        rows.append(f"{NAME[s]} & " + " & ".join(cells) + r" \\")
        if s == "torus":
            rows.append(r"\midrule")
    rows += [r"\bottomrule", r"\end{tabular}"]
    write("rr-cost.tex", rows, "docs/research/paper-real-read/tables-sweep.md (analyse_real.py sweep)")


