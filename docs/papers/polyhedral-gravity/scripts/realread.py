# ------------------------------------------------------------------ helpers

def sci(x: float, digits: int = 1) -> str:
    if not math.isfinite(x):
        return "---"
    m, e = f"{x:.{digits}e}".split("e")
    if int(e) == 0:
        return f"${m}$"
    return f"${m}\\times10^{{{int(e)}}}$"


def num(s: str) -> float:
    s = s.strip().replace("−", "-")
    return float(s)


def write(name: str, rows: list[str], source: str) -> None:
    TEX.mkdir(exist_ok=True)
    (TEX / name).write_text(f"% generated by scripts/realread.py from {source}\n" + "\n".join(rows) + "\n",
                            encoding="utf-8")


def md_sections(path: pathlib.Path) -> dict[str, list[list[str]]]:
    """Every markdown table under each '## ' heading, as rows of cells (header row kept)."""
    out: dict[str, list[list[str]]] = {}
    head = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            head = line[3:].strip()
            out[head] = []
        elif line.startswith("|") and head:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            out[head].append(cells)
    return out


def section(secs: dict[str, list[list[str]]], prefix: str) -> list[list[str]]:
    for k, v in secs.items():
        if k.startswith(prefix):
            return v
    raise KeyError(prefix)


CELL = re.compile(r"^\s*([0-9.eE+\-−]+)\s*(?:\[[^\]]*\])?\s*(?:\((-?[0-9.]+)\s*(?:\[([^\]]*)\])?\))?")


def rms_order(cell: str) -> tuple[float, float, str]:
    """'9.5e-3 [1e-3–1e-2] (1.98 [1.9–2.5])' -> (9.5e-3, 1.98, '1.9–2.5')."""
    m = CELL.match(cell)
    if not m:
        return float("nan"), float("nan"), ""
    return num(m.group(1)), float(m.group(2)) if m.group(2) else float("nan"), m.group(3) or ""


