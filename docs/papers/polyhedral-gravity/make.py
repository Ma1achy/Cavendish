SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
INK, INK2, GRID = "#0b0b0b", "#52514e", "#d9d8d4"
MARKERS = ["o", "s", "^", "D", "v", "P", "X"]


def style() -> None:
    import matplotlib as mpl

    mpl.rcParams.update({
        "font.family": "serif", "font.size": 8, "axes.edgecolor": INK2, "axes.labelcolor": INK,
        "xtick.color": INK2, "ytick.color": INK2, "axes.grid": True, "grid.color": GRID,
        "grid.linewidth": 0.5, "axes.spines.top": False, "axes.spines.right": False,
        "lines.linewidth": 1.4, "lines.markersize": 4, "legend.frameon": False,
        "savefig.bbox": "tight", "pdf.fonttype": 42,
    })


def fig_convergence() -> None:
    import matplotlib.pyplot as plt

    conv = json.loads((DATA / "convergence.json").read_text(encoding="utf-8"))["triple"]
    shown = ("zero_one", "ss4", "frac", "frac_cen", "frac_cen_q")
    fig, axes = plt.subplots(1, 3, figsize=(6.8, 2.5), sharey=True)
    for ax, name in zip(axes, ("cube_aligned", "cube", "sphere")):
        ns = conv[name]["n"]
        h = [1.0 / n for n in ns]
        for k, rep in enumerate(shown):
            r = conv[name]["1.5"]["reps"][rep]
            ax.loglog(h, r["err"], marker=MARKERS[k], color=SERIES[k],
                      label=f"{LABELS[rep]}")
        ax.set_title(name.replace("_", " "), fontsize=8, color=INK)
        ax.set_xlabel("pitch $h$ (m)")
        ax.set_xticks(h, [f"1/{n}" for n in ns])
        ax.minorticks_off()
    axes[0].set_ylabel("phase error at 1.5 m (rad)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=3, bbox_to_anchor=(0.5, 1.13), fontsize=7)
    fig.savefig(FIG / "convergence.pdf")
    plt.close(fig)


def parse_table(path: pathlib.Path) -> list[list[str]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    return [ln.split() for ln in lines[1:] if ln.strip()]


def fig_farfield() -> None:
    import matplotlib.pyplot as plt

    rows = parse_table(DATA / "farfield.txt")
    ratio = [float(r[0]) for r in rows]
    cols = {"triple product $r_1\\cdot(r_2\\times r_3)$": 2, "$h_f\\,2A_f$ numerator": 4,
            "$h_f\\,2A_f$, naive $\\ln$ ratio": 6}
    fig, ax = plt.subplots(figsize=(3.3, 2.5))
    for k, (label, c) in enumerate(cols.items()):
        ys = [float(r[c]) for r in rows]
        ax.loglog(ratio, ys, marker=MARKERS[k], color=SERIES[k], label=label)
    eps = 2.2e-16
    ref = [eps * x**2 for x in ratio]
    ax.loglog(ratio, ref, color=INK2, linestyle="--", linewidth=0.8, label=r"$\varepsilon (R/s)^2$")
    ax.set_xlabel("distance over cube side, $R/s$")
    ax.set_ylabel("relative error of $g$")
    ax.legend(fontsize=6.5, loc="upper left")
    fig.savefig(FIG / "farfield.pdf")
    plt.close(fig)


def fig_nearedge() -> None:
    import matplotlib.pyplot as plt

    rows = parse_table(DATA / "nearedge.txt")
    d = [float(r[0]) for r in rows]
    naive = [float(r[2]) if r[2] != "inf" else float("nan") for r in rows]
    hk = [float(r[3]) for r in rows]
    exact = [float(r[1]) for r in rows]
    fig, ax = plt.subplots(figsize=(3.3, 2.5))
    ax.loglog(d, naive, marker="o", color=SERIES[0], label="direct $a+b-\\ell$")
    ax.loglog(d, hk, marker="s", color=SERIES[1], label="$r_0^2/(r-\\ell_1)+r_0^2/(r+\\ell_2)$")
    # Conditioning of the input: the point is known to eps|p| ~ 1e-17 m, so L moves by
    # (eps |p| / d) / L. This is the floor no formula can beat.
    floor = [2.2e-16 * 0.45 / x / big_l for x, big_l in zip(d, exact)]
    ax.loglog(d, floor, color=INK2, linestyle="--", linewidth=0.8,
              label=r"input rounding $\varepsilon|p|/(dL)$")
    ax.set_xlabel("distance from the edge, $d$ (m)")
    ax.set_ylabel("relative error of $L_e$")
    ax.legend(fontsize=6.5, loc="upper right")
    fig.savefig(FIG / "nearedge.pdf")
    plt.close(fig)


def fig_crosscheck() -> None:
    import matplotlib.pyplot as plt

    ref = json.loads((DATA / "mp_reference.json").read_text(encoding="utf-8"))
    fig, ax = plt.subplots(figsize=(3.3, 2.5))
    for k, (who, key, mk) in enumerate((("this form", "ours_g", "o"), ("ESA (Tsoulis 2012)", "esa_g", "s"))):
        for j, (name, rows) in enumerate(ref["bodies"].items()):
            rs = sorted({r["R"] for r in rows})
            worst = [max(r[key] for r in rows if r["R"] == x) for x in rs]
            ax.loglog(rs, worst, marker=mk, color=SERIES[k], alpha=0.75, linewidth=0.9,
                      label=who if j == 0 else None)
    ax.set_xlabel("distance from the body's centre (m)")
    ax.set_ylabel("relative error of $g$ (vs 40 digits)")
    ax.legend(fontsize=6.5, loc="upper left")
    fig.savefig(FIG / "crosscheck.pdf")
    plt.close(fig)


def budget() -> None:
    """The error budget table for AION-10 (1.4 t body, centre 1.5 m from the lower arm,
    h = 1/64 m): measured rows from convergence.json and mp_reference.json, derived rows marked."""
    conv = json.loads((DATA / "convergence.json").read_text(encoding="utf-8"))["edges"]
    ref = json.loads((DATA / "mp_reference.json").read_text(encoding="utf-8"))

    def worst(rep: str) -> float:
        return max(conv[b]["1.5"]["reps"][rep]["err"][-1] for b in BODIES)

    sig = max(conv[b]["1.5"]["signal"] for b in BODIES)
    rel = max(r["ours_g"] for rows in ref["bodies"].values() for r in rows if r["R"] <= 1.5 + 1e-9)
    rows = [
        ("boundary cells as sampled fill $4^3$ (Cavendish today)", worst("ss4"), "measured"),
        ("boundary cells as fill + centroid", worst("frac_cen"), "measured"),
        ("boundary cells as fill + centroid + second moment", worst("frac_cen_q"), "measured"),
        ("closed form, whole body or clipped pieces (f64 rounding)", rel * sig, "measured"),
        ("octree far field (S5 walk tolerance)", 1e-10, "design"),
        ("flight quadrature (audited read, \\texttt{PHASE\\_TOLERANCE})", 1e-10, "design"),
        ("shot-noise floor, rad\\,Hz$^{-1/2}$ (AION-10 baseline, for scale)", 1e-4, "reference"),
    ]
    out = [r"\begin{tabular}{lrl}", r"\toprule", r"contribution & phase (rad) & source \\",
           r"\midrule"]
    out += [f"{a} & {sci(v)} & {s} \\\\" for a, v, s in rows]
    out += [r"\bottomrule", r"\end{tabular}", ""]
    TEX.mkdir(exist_ok=True)
    (TEX / "budget.tex").write_text("\n".join(out), encoding="utf-8")
    (TEX / "numbers.tex").write_text(
        f"\\newcommand{{\\SignalMax}}{{{sig:.0f}}}\n"
        f"\\newcommand{{\\ClosedRel}}{{{sci(rel)}}}\n", encoding="utf-8")


