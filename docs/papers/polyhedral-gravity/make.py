def phase(values: list[float], di: int) -> float:
    v = [abs(x) for x in values[di * 3:(di + 1) * 3]]
    return K_EFF_T2 * max(v)


def convergence(suffix: str) -> dict[str, dict[str, object]]:
    """Per body, distance and representation: RMS (over placements) of the worst-direction phase
    error at each pitch, and the least-squares order. tables.py's definition, recomputed here."""
    import numpy as np

    out: dict[str, dict[str, object]] = {}
    for name in BODIES:
        runs = json.loads((DATA / f"{name}{suffix}.json").read_text(encoding="utf-8"))
        ns = sorted({r["n"] for r in runs})
        body: dict[str, object] = {"n": ns}
        for dist in (1.5, 10.0):
            di = DISTANCES.index(dist)
            sig = float(np.mean([phase(r["signal_dgz"], di) for r in runs]))
            reps: dict[str, object] = {}
            for rep in REPS:
                errs = [math.sqrt(float(np.mean(np.square(
                    [phase(r[rep]["dgz"], di) for r in runs if r["n"] == n])))) for n in ns]
                order = float(np.polyfit(np.log([1.0 / n for n in ns]), np.log(errs), 1)[0])
                reps[rep] = {"err": errs, "order": order}
            body[f"{dist:g}"] = {"signal": sig, "reps": reps,
                                 "cells": [int(np.mean([r["boundary_cells"] for r in runs
                                                        if r["n"] == n])) for n in ns]}
        out[name] = body
    return out


def sci(x: float) -> str:
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def latex_table(conv: dict[str, dict[str, object]], dist: float) -> str:
    key = f"{dist:g}"
    head = " & ".join(n.replace("_", r"\_") for n in BODIES)
    rows = [r"\begin{tabular}{l" + "r" * len(BODIES) + "}", r"\toprule",
            f"representation & {head} \\\\", r"\midrule"]
    sig = " & ".join(f"\\textit{{{conv[b][key]['signal']:.3g}}}" for b in BODIES)  # type: ignore[index]
    rows.append(f"\\textit{{signal}} & {sig} \\\\")
    for rep in REPS:
        cells = []
        for b in BODIES:
            r = conv[b][key]["reps"][rep]  # type: ignore[index]
            cells.append(f"{sci(r['err'][-1])} ({r['order']:.1f})")
        rows.append(f"{LABELS[rep]} & " + " & ".join(cells) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(rows)


