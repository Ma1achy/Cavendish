"""Key numbers for the note's §§2–5, per shape, from data/tree-*.json: data/keys.md.

    python keys.py
"""

from __future__ import annotations

import json

import common as C


def main() -> None:
    out = ["# Key numbers (generated by keys.py)", ""]
    out += ["## Adaptive refinement against the baselines (surface cost per point, µs)", "",
            "| shape | whole mesh | finest exact pieces | " + " | ".join(f"adaptive {d} m, 1e-8" for d in C.DISTANCES)
            + " | adaptive 1.5 m, 1e-10 | max \\|error\\|/B over all designs | 20 m design read at 0.5 m, 1e-8 |",
            "|---|---|---|" + "---|" * len(C.DISTANCES) + "---|---|---|"]
    walks = ["| shape | tower | octree, geometric b | octree, tight b | BVH, tight b | BVH over free boxes | visits octree / BVH | \\|error\\| / B (worst) |",
             "|---|---|---|---|---|---|---|---|"]
    for s in C.SHAPES:
        p = C.DATA / f"tree-{s}.json"
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        a = r["adaptive"]
        worst = max(abs(v["error_at_towers"][v["design_tower"]]) / float(k.split("/")[1])
                    for k, v in a.items() if "/" in k)
        row = [f"{a['whole_mesh']['cost_ns_per_point'] / 1e3:.3g}", f"{a['uniform_finest_exact']['cost_ns_per_point'] / 1e3:.3g}"]
        row += [f"{a[f'{d}m/1e-08']['cost_ns_per_point'] / 1e3:.3g}" for d in C.DISTANCES]
        row += [f"{a['1.5m/1e-10']['cost_ns_per_point'] / 1e3:.3g}", f"{worst:.2g}",
                f"{abs(a['20.0m/1e-08']['error_at_towers'][0]):.1e}"]
        out.append(f"| {C.NAME[s]} | " + " | ".join(row) + " |")
        w = r["walks"]
        for d in C.DISTANCES:
            k = f"{d}m/1e-08"
            g = w.get(f"octree/octree/geometric/{k}")
            t = w.get(f"octree/octree/tight/{k}")
            b = w.get(f"octree/bvh/tight/{k}")
            f = w.get(f"sweep/bvh/tight/{k}")
            err = max(abs(x["error"]) for x in (g, t, b, f)) / 1e-8
            walks.append(f"| {C.NAME[s]} | {d} m | {g['cost_ns_per_point'] / 1e3:.3g} | {t['cost_ns_per_point'] / 1e3:.3g} | "
                         f"{b['cost_ns_per_point'] / 1e3:.3g} | {f['cost_ns_per_point'] / 1e3:.3g} | {t['visits']} / {b['visits']} | {err:.1e} |")
    out += ["", "## The error-bounded walk at B = 1e-8 rad (cost per point, µs)", ""] + walks
    (C.DATA / "keys.md").write_text("\n".join(out) + "\n", encoding = "utf-8")


if __name__ == "__main__":
    main()
