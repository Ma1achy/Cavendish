"""The series of a uniform axis-aligned box to l = 6, its coefficients, and the C9 check.

    python series.py gen     # writes bench/src/kappa.rs (the κ table) and data/kappa.json
    python series.py check   # C9: series against a 40-digit closed form (data/series-check.json)

For a box of mass M, centre c and half-sides a, and R = p − c,

    U(p) = M [1/R + Σ_{l = 2, 4, 6} E_l(R̂)/R^(l+1)],   E_l(n) = ⟨|y|^l P_l(n·ŷ)⟩_box,

the Legendre expansion of 1/|R − y| averaged over the box. |y|^l P_l(n·ŷ) = Σ_k p_lk (n·y)^(l−2k)
|y|^(2k) |n|^(2k) is homogeneous of degree l in y and in n. Averaged over the box only even powers
of y survive, ⟨y^e⟩ = Π a_i^(e_i)/(e_i + 1) = μ_e, so E_l(n) = Σ_f β_f n^f over even monomials f of
degree l, with β_f = Σ_e κ_{e,f} μ_e: 3, 6 and 10 numbers per box for l = 2, 4, 6. A cube has β₂ = 0.
"""

from __future__ import annotations

import itertools
import json
import sys

import numpy as np

import common as C


def monomials(l: int) -> list[tuple[int, int, int]]:
    """Even exponent triples of degree l, in the bench's order."""
    return [(i, j, l - i - j) for i in range(l, -1, -2) for j in range(l - i, -1, -2)]


def kappa() -> dict[int, list[list[float]]]:
    """κ[l][e][f]: coefficient of y^e n^f in |y|^l P_l(n·ŷ), homogenised."""
    import sympy as sp

    y = sp.symbols("y0:3")
    n = sp.symbols("n0:3")
    out = {}
    for l in (2, 4, 6):
        t = sp.symbols("t")
        pl = sp.Poly(sp.legendre(l, t), t)
        ny = sum(a * b for a, b in zip(n, y))
        yy = sum(a * a for a in y)
        nn = sum(a * a for a in n)
        expr = 0
        for (power,), coef in zip(pl.monoms(), pl.coeffs()):
            k = (l - power) // 2
            expr += coef * ny**power * yy**k * nn**k
        poly = sp.Poly(sp.expand(expr), *y, *n)
        mono = monomials(l)
        table = [[0.0] * len(mono) for _ in mono]
        for exps, coef in zip(poly.monoms(), poly.coeffs()):
            e, f = exps[:3], exps[3:]
            if e in mono:
                table[mono.index(e)][mono.index(f)] = float(coef)
        out[l] = table
    return out


def betas(half: np.ndarray, kap: dict[int, list[list[float]]]) -> dict[int, np.ndarray]:
    """β per box (N, nf) for each l, from half-sides (N, 3)."""
    out = {}
    for l, table in kap.items():
        mono = monomials(l)
        mu = np.stack([np.prod(half ** np.array(e) / (np.array(e) + 1.0), axis = 1) for e in mono], axis = 1)
        out[l] = mu @ np.array(table)
    return out


def series_u(mass: np.ndarray, centre: np.ndarray, half: np.ndarray, pts: np.ndarray, lmax: int,
             kap: dict[int, list[list[float]]]) -> np.ndarray:
    """U at pts (M, 3) summed over boxes, through order lmax (0, 2, 4, 6)."""
    b = betas(half, kap)
    out = np.zeros(len(pts))
    step = max(1, 2_000_000 // max(len(pts), 1))
    for s in range(0, len(mass), step):
        d = pts[:, None] - centre[None, s:s + step]
        r = np.linalg.norm(d, axis = 2)
        u = 1.0 / r
        for l in (2, 4, 6):
            if l > lmax:
                break
            mono = monomials(l)
            poly = sum(b[l][None, s:s + step, i] * np.prod(d ** np.array(f), axis = 2) for i, f in enumerate(mono))
            u = u + poly / r ** (2 * l + 1)
        out += (mass[None, s:s + step] * u).sum(axis = 1)
    return out


def gen() -> None:
    kap = kappa()
    C.save_json("kappa.json", {str(k): v for k, v in kap.items()})
    lines = ["//! Generated by `series.py gen`: the κ tables of a box's series (see series.py).",
             "", "use crate::geom::V;", ""]
    for l, table in kap.items():
        nf = len(table)
        rows = ", ".join("[" + ", ".join(repr(x) for x in row) + "]" for row in table)
        lines.append(f"pub const K{l}: [[f64; {nf}]; {nf}] = [{rows}];")
        lines.append(f"pub const E{l}: [[i32; 3]; {nf}] = {[list(e) for e in monomials(l)]};")
    lines += ["",
              "fn mu<const N: usize>(half: V, e: &[[i32; 3]; N]) -> [f64; N] {",
              "    let mut out = [0.0; N];",
              "    for (o, x) in out.iter_mut().zip(e) {",
              "        *o = (0..3).map(|i| half[i].powi(x[i]) / f64::from(x[i] + 1)).product();",
              "    }",
              "    out",
              "}",
              "",
              "fn fold<const N: usize>(mu: [f64; N], k: &[[f64; N]; N]) -> [f64; N] {",
              "    let mut out = [0.0; N];",
              "    for (e, m) in mu.iter().enumerate() {",
              "        for f in 0..N {",
              "            out[f] += m * k[e][f];",
              "        }",
              "    }",
              "    out",
              "}",
              "",
              "/// β for l = 2, 4, 6 of a box with half-sides `half` (m).",
              "pub fn betas(half: V) -> ([f64; 3], [f64; 6], [f64; 10]) {",
              "    (fold(mu(half, &E2), &K2), fold(mu(half, &E4), &K4), fold(mu(half, &E6), &K6))",
              "}"]
    (C.HERE / "bench" / "src" / "kappa.rs").write_text("\n".join(lines) + "\n", encoding = "utf-8")
    print("wrote kappa.rs")


def nagy_mp(lo: np.ndarray, hi: np.ndarray, p: np.ndarray) -> object:
    """∫dV/r over the box [lo, hi] from point p at 40 digits (Nagy's corner sum)."""
    import mpmath as mp

    mp.mp.dps = 40
    tot = mp.mpf(0)
    for i, j, k in itertools.product((0, 1), repeat = 3):
        x = mp.mpf(float((hi if i else lo)[0])) - mp.mpf(float(p[0]))
        y = mp.mpf(float((hi if j else lo)[1])) - mp.mpf(float(p[1]))
        z = mp.mpf(float((hi if k else lo)[2])) - mp.mpf(float(p[2]))
        r = mp.sqrt(x * x + y * y + z * z)
        f = (x * y * mp.log(z + r) + y * z * mp.log(x + r) + z * x * mp.log(y + r)
             - x * x / 2 * mp.atan(y * z / (x * r)) - y * y / 2 * mp.atan(z * x / (y * r))
             - z * z / 2 * mp.atan(x * y / (z * r)))
        tot += (-1) ** (i + j + k + 1) * f
    return tot


def check() -> None:
    """C9: relative error of the l ≤ 2, 4, 6 series against 40 digits, for a cube and two boxes,
    at R/s from 2 to 100 along a skew direction; fitted slopes in s/R."""
    import mpmath as mp

    kap = {int(k): v for k, v in C.load_json("kappa.json").items()}  # type: ignore[union-attr]
    d = np.array([0.37, 0.61, 0.70])
    d /= np.linalg.norm(d)
    ratios = np.geomspace(2, 100, 9)
    out = {}
    for name, half in (("cube", [0.5, 0.5, 0.5]), ("box 1:2:3", [0.25, 0.5, 0.75]), ("slab 4:4:1", [1.0, 1.0, 0.25])):
        a = np.array(half)
        s = 2 * float(np.linalg.norm(a))  # the box's diameter
        rows = {}
        for lmax in (0, 2, 4, 6):
            errs = []
            for q in ratios:
                p = d * q * s
                ref = nagy_mp(-a, a, p)
                u = series_u(np.array([8 * a.prod()]), np.zeros((1, 3)), a[None], p[None], lmax, kap)[0]
                errs.append(float(abs((mp.mpf(float(u)) - ref) / ref)))
            ok = np.array(errs) > 1e-13  # above the f64 evaluation floor
            sl = np.polyfit(np.log(1 / ratios[ok]), np.log(np.array(errs)[ok]), 1)[0]
            rows[lmax] = {"errors": errs, "slope": float(sl)}
        out[name] = {"half": half, "ratios": ratios.tolist(), "series": rows}
        print(name, {k: (round(v["slope"], 2), f"{v['errors'][-1]:.1e}") for k, v in rows.items()})
    C.save_json("series-check.json", out)


if __name__ == "__main__":
    {"gen": gen, "check": check}[sys.argv[1]]()
