"""Tables for the note from data/tree-*.json, data/gpu-*.json and the checks: data/tables.md.

    python summary.py
"""

from __future__ import annotations

import json

import common as C


def us(x: float) -> str:
    return f"{x / 1e3:.3g}"


def main() -> None:
    out = ["# Tables (generated by summary.py)", ""]
    trees = {s: json.loads((C.DATA / f"tree-{s}.json").read_text()) for s in C.SHAPES if (C.DATA / f"tree-{s}.json").exists()}

    out += ["## Part 2: adaptive surface refinement (surface cost per point, µs; leaves; memory KiB; |error| at the design tower)", ""]
    out += ["| shape | design tower | B (rad) | cost (µs) | memory (KiB) | leaves by level and kind | \\|error\\| at design tower (rad) | error at the 0.5 m tower (rad) |",
            "|---|---|---|---|---|---|---|---|"]
    for s, r in trees.items():
        a = r["adaptive"]
        for d in C.DISTANCES:
            for b in (1e-6, 1e-8, 1e-10):
                x = a[f"{d}m/{b:g}"]
                lv = ", ".join(f"{k}: {v}" for k, v in sorted(x["leaves"].items()))
                out.append(f"| {C.NAME[s]} | {d} m | {b:g} | {us(x['cost_ns_per_point'])} | {x['memory_bytes'] / 1024:.0f} | {lv} | "
                           f"{abs(x['error_at_towers'][x['design_tower']]):.1e} | {abs(x['error_at_towers'][0]):.1e} |")
        f, m = a["uniform_finest_exact"], a["whole_mesh"]
        out.append(f"| {C.NAME[s]} | baseline | finest exact pieces | {us(f['cost_ns_per_point'])} | {f['memory_bytes'] / 1024:.0f} | "
                   f"{f['pieces']} pieces, {f['piece_triangles']:.0f} triangles | rounding | |")
        out.append(f"| {C.NAME[s]} | baseline | whole mesh | {us(m['cost_ns_per_point'])} | {m['memory_bytes'] / 1024:.0f} | {m['triangles']} triangles | rounding | |")
    out.append("")

    out += ["## Part 3 and 5: the error-bounded walk (cost per point, µs; node visits; |error|; bound sum; worst error/bound)", ""]
    out += ["| shape | tree | tower | B | cost (µs) | visits | nodes | \\|error\\| | Σ bounds | worst err/bound | over bound | accepted |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s, r in trees.items():
        for key, x in r["walks"].items():
            kind, tree, radius, dist, b = key.split("/")[:5]
            ctrl = key.endswith("control")
            acc = ", ".join(f"{k} {v}" for k, v in x["accepted"].items() if v)
            out.append(f"| {C.NAME[s]} | {kind} interior, {tree} ({radius}){' CONTROL' if ctrl else ''} | {dist} | {b} | {us(x['cost_ns_per_point'])} | "
                       f"{x['visits']} | {x.get('nodes', '')} | {abs(x['error']):.1e} | {x['bound_sum']:.1e} | {x['worst_error_over_bound']:.2f} | "
                       f"{x['nodes_over_bound']} | {acc} |")
    out.append("")

    out += ["## Part 4: the interior alone, octree blocks against free (sweep) boxes, series to l = 2 / 4 / 6", ""]
    out += ["| shape | interior | boxes | tower | B | cost l≤2 (µs) | cost l≤4 | cost l≤6 | closed forms at l≤2 / 4 / 6 | \\|error\\| l≤6 |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for s, r in trees.items():
        it = r["interior"]
        for kind in ("octree", "sweep"):
            for d in C.DISTANCES:
                for b in (1e-6, 1e-10):
                    xs = [it[f"{kind}/{d}m/{b:g}/l{l}"] for l in (2, 4, 6)]
                    out.append(f"| {C.NAME[s]} | {kind} | {xs[0]['boxes']} | {d} m | {b:g} | " + " | ".join(us(x["cost_ns_per_point"]) for x in xs)
                               + " | " + " / ".join(str(x["used"]["closed"]) for x in xs) + f" | {abs(xs[2]['error']):.1e} |")
            a = it[f"{kind}/aspect"]
            out.append(f"| {C.NAME[s]} | {kind} aspect ratio | median {a['median']:.1f}, max {a['max']:.0f} | | | | | | | |")
    out.append("")
    out += ["## Part 6: GPU kernels on the GTX 1660 SUPER (indicative; best of three runs)", ""]
    out += ["| set | kernel | precision | elements | ns per element per point | CPU f64 ns (same run, 1 thread) | max rel. error of U | max phase error per tower (rad) |",
            "|---|---|---|---|---|---|---|---|"]
    for f in sorted(C.DATA.glob("gpu-*-L*.json")):
        g = json.loads(f.read_text())
        for r in g["runs"]:
            if "error" in r:
                continue
            out.append(f"| {f.stem} | {r['kernel']} | {r['precision']} | {r['elements']} | {r['ns_per_element_point']:.3g} | "
                       f"{r['cpu_f64_ns_per_element_point']:.3g} | {r['max_rel_err_u']:.1e} | {max(float(x) for x in r['phase_error_per_tower']):.1e} |")
        out.append(f"| {f.stem} | FMA rate | | | {g['fma_rate']} | | | |")
    out.append("")
    (C.DATA / "tables.md").write_text("\n".join(out), encoding = "utf-8")


if __name__ == "__main__":
    main()
